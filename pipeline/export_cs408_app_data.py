"""Export the parsed 408 bank into the application data module."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "pipeline" / "output"
APP_DATA = ROOT / "functions" / "cs408-data.mjs"


def main() -> None:
    knowledge = json.loads((OUTPUT / "cs408-knowledge.json").read_text(encoding="utf-8"))
    papers = json.loads((OUTPUT / "cs408-papers.json").read_text(encoding="utf-8"))
    tags = json.loads((OUTPUT / "cs408-tags.json").read_text(encoding="utf-8"))
    rows = [json.loads(line) for line in (OUTPUT / "cs408-bank.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]

    questions = []
    for row in rows:
        tag = tags.get(row["id"], {})
        chapter = tag.get("chapter")
        subject = tag.get("subject") or (chapter or "DS")[:2]
        nodes = []
        if chapter:
            nodes.append({"code": chapter, "role": "main", "weight": 100})
        nodes.append({"code": subject, "role": "aux", "weight": 50})
        score = row.get("score")
        if row["qtype"] == "single_choice":
            score_x2 = 4
            score_source = "section"
        elif score:
            score_x2 = score * 2
            score_source = "source"
        else:
            score_x2 = 20
            score_source = "placeholder"
        figures = [
            {
                "id": f"{row['id']}-fig-{index}",
                "url": figure["url"],
                "width": figure.get("width"),
                "height": figure.get("height"),
                "alt": figure.get("alt") or figure.get("caption") or "408 题目图形",
                "role": figure.get("role"),
            }
            for index, figure in enumerate(row.get("figures") or [])
        ]
        options = [
            {
                "label": option["label"],
                "source_label": option.get("source_label"),
                "text": option.get("text") or "",
                "image": option.get("image"),
            }
            for option in row.get("options") or []
        ]
        questions.append({
            "id": row["id"],
            "subject": "cs408",
            "paper_id": row["paper_id"],
            "seq_label": row["seq_label"],
            "year": row["year"],
            "number": row["number"],
            "title": row["title"],
            "section": row["section"],
            "qtype": row["qtype"],
            "question_type_label": row.get("question_type_label"),
            "question_html": row["question_html"],
            "question_text": row["question_text"],
            "stem_latex": row["question_text"],
            "options": options,
            "options_json": [
                {"label": option["label"], "latex": option.get("text") or ""}
                for option in options
            ] or None,
            "sub_items_json": None,
            "answer_latex": row.get("answer") or "",
            "answer_html": row.get("answer_html") or "",
            "answer_text": row.get("answer_text") or "",
            "explanation": row.get("explanation") or "",
            "has_explanation": bool(row.get("has_explanation")),
            "score_x2": score_x2,
            "score_source": score_source,
            "difficulty": "medium",
            "difficulty_source": "unset",
            "source": "real",
            "is_fixture": False,
            "has_figure": bool(figures),
            "figure_asset_id": figures[0]["id"] if figures else None,
            "figure_assets": figures,
            "figures": figures,
            "knowledge": nodes,
            "content_hash": row["content_hash"],
            "status": "published",
            "data_notes": row.get("data_notes") or [],
        })

    knowledge_nodes = [
        {
            "id": node["id"],
            "parent_id": node["parent_id"],
            "code": node["code"],
            "name": node["name"],
            "level": node["level"],
            "aliases": node.get("aliases") or [node["name"]],
            "subject": "cs408",
        }
        for node in knowledge
    ]
    paper_rows = [
        {
            **paper,
            "subject": "cs408",
            "title": f"{paper['year']} 年考研 408 真题",
            "total_score_x2": 300,
            "auto_score_x2": 160,
            "paper_type": "real_exam",
        }
        for paper in papers
    ]
    payload = "// Generated by pipeline/export_cs408_app_data.py. Do not edit by hand.\n"
    payload += "export const cs408Knowledge = " + json.dumps(knowledge_nodes, ensure_ascii=False) + ";\n"
    payload += "export const cs408Papers = " + json.dumps(paper_rows, ensure_ascii=False) + ";\n"
    payload += "export const cs408Questions = " + json.dumps(questions, ensure_ascii=False) + ";\n"
    APP_DATA.write_text(payload, encoding="utf-8")
    print(json.dumps({
        "questions": len(questions),
        "knowledge": len(knowledge_nodes),
        "papers": len(paper_rows),
        "bytes": APP_DATA.stat().st_size,
        "out": str(APP_DATA),
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
