"""Export selected pilot-bank years as app data (real questions + full knowledge tree)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "pipeline" / "output"
APP_DATA = ROOT / "functions" / "real-data.mjs"


def norm_math(text: str) -> str:
    if not text:
        return text
    if "$" not in text and not any("一" <= ch <= "鿿" for ch in text):
        return f"${text.strip()}$"
    return text


def main() -> None:
    tree = json.loads((ROOT / "contracts" / "knowledge-tree.json").read_text(encoding="utf-8"))
    nodes = [{
        "id": node["code"], "parent_id": (tree[[n["code"] for n in tree].index(node["parent_id"])]["code"] if node["parent_id"] else None),
        "code": node["code"], "name": node["name"], "level": node["level"], "aliases": node.get("aliases_json", [node["name"]]),
    } for node in tree]
    rows = [json.loads(line) for line in (OUTPUT / "pilot-bank.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
    explanations = {}
    explanation_path = OUTPUT / "explanations.jsonl"
    if explanation_path.exists():
        for line in explanation_path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                item = json.loads(line)
                if item.get("summary") and item.get("steps"):
                    explanations[item["content_hash"]] = item
    selected = rows
    figure_path = OUTPUT / "figure-assets.json"
    figures = json.loads(figure_path.read_text(encoding="utf-8")) if figure_path.exists() else {}
    questions = []
    for row in selected:
        enriched = explanations.get(row["content_hash"])
        explanation = enriched["summary"] if enriched else row["approach_raw"]
        steps = enriched["steps"] if enriched else [step["desc"] for step in row["rubric_draft"]["steps"]]
        number = row["seq_label"].rsplit("-", 1)[-1]
        figure = figures.get(f"{row['year']}:{number}")
        questions.append({
            "id": row["id"], "paper_id": None,
            "seq_label": row["seq_label"].rsplit("-", 1)[-1], "year": row["year"],
            "section": row["section"], "qtype": row["qtype"],
            "stem_latex": norm_math(row["stem_latex"]),
            "sub_items_json": [{"label": item.get("label", ""), "prompt_latex": norm_math(item.get("prompt_latex", ""))} for item in (row["sub_items_json"] or [])] or None,
            "options_json": [{"label": item.get("label", ""), "latex": norm_math(item.get("latex", ""))} for item in (row["options_json"] or [])] or None,
            "answer_latex": row["answer_latex"], "answer_source": row["answer_source"],
            "solution_latex": None, "score_x2": row["score_x2"],
            "difficulty": row["difficulty"], "difficulty_obs": None,
            "difficulty_source": row["difficulty_source"],
            "est_minutes": None, "has_figure": bool(figure),
            "figure_asset_id": figure["id"] if figure else None,
            "figure_assets": [figure] if figure else [],
            "source": "real",
            "generator_meta_json": {
                "score_source": row["score_source"],
                "exam_point_raw": row["exam_point_raw"],
                "approach_raw": explanation,
                "solution_steps": steps,
                "explanation_source": "model_enriched" if enriched else "official_rubric",
            },
            "rubric_json": None, "rubric_source": None, "rubric_version": 1,
            "content_hash": row["content_hash"], "status": "published",
            "knowledge": row["knowledge"], "is_fixture": False,
        })
    payload = "// Generated by pipeline/export_app_data.py. Do not edit by hand.\n"
    payload += "export const realKnowledge = " + json.dumps(nodes, ensure_ascii=False) + ";\n"
    payload += "export const realQuestions = " + json.dumps(questions, ensure_ascii=False) + ";\n"
    APP_DATA.write_text(payload, encoding="utf-8")
    print(json.dumps({"questions": len(questions), "years": sorted({q["year"] for q in questions}), "knowledge": len(nodes), "out": str(APP_DATA)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
